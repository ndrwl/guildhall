// Secrets plan and receipt schemas (docs/secrets.md#the-steward-pushes-them).
const (
	SecretsPlanSchema    = secretsPlanSchemaPrefix + "1"
	SecretsReceiptSchema = "guildhall.secrets-receipt/1"

	secretsPlanSchemaPrefix  = "guildhall.secrets-plan/"
	secretsPlanSchemaVersion = 1
)

// StatusCheckFailed is a machine whose secrets file was published and read back but whose secrets check did not
// decrypt it to the planned names with the machine's own key.
const StatusCheckFailed = "check_failed"

// StatusInstallFailed is a machine whose new ciphertext was put beside its secrets file and read back but which
// secrets install refused to swap in, so its secrets file is unchanged; the step's output names what refused.
const StatusInstallFailed = "install_failed"

// SopsConfigFile is the sops configuration generated from the roster at the root of the private config: one creation
// rule per machine with an age_recipient, encrypting its secrets file to its key and the recovery key.
const SopsConfigFile = ".sops.yaml"

// RemoteSecretsFile is where a machine's secrets file is published, relative to the home directory of its Guildhall
// account, as scp reads a relative path: the file secrets.DefaultPaths names there.
const RemoteSecretsFile = ".config/guildhall/" + secrets.File

// SecretsFile is the private config's ciphertext for machine, a slash-separated path below the checkout.
func SecretsFile(machine string) string { return "secrets/" + machine + ".sops.yaml" }

// SopsConfig is the .sops.yaml generated from the roster: one rule per machine with an age_recipient, encrypting
// its secrets file to that key and the recovery key, so a hand run of sops on a file encrypts it as the Steward does.
// Each machine has its own file, so removing one machine re-encrypts no other machine's file.
func SopsConfig(r *Roster) ([]byte, error) {
	if r.RecoveryRecipient == "" {
		return nil, errors.New("the roster has no recovery_recipient, the Guildmaster's recovery key every secrets file is also encrypted to")
	}
	var b strings.Builder
	b.WriteString("# Generated by guildhall steward secrets set from roster.toml; do not edit.\ncreation_rules:\n")
	for _, m := range r.Machines {
		if m.AgeRecipient == "" {
			continue
		}
		fmt.Fprintf(&b, "  - path_regex: ^secrets/%s\\.sops\\.yaml$\n    age: %s,%s\n", strings.ReplaceAll(m.Label, ".", `\.`), m.AgeRecipient, r.RecoveryRecipient)
	}
	return []byte(b.String()), nil
}

// recipients are the keys machine m's secrets file is encrypted to: its own and the recovery key, sorted.
func (r *Roster) recipients(m Machine) []string {
	return slices.Sorted(slices.Values([]string{m.AgeRecipient, r.RecoveryRecipient}))
}

// Secrets sets and pushes the machines' secrets from the private config checkout (docs/secrets.md#the-steward-pushes-them):
// each value is encrypted at once to its machine's key and the recovery key and committed as ciphertext, and a plan
// approved by its digest copies a machine's ciphertext beside its secrets file with scp, reads it back, has the
// machine install it only once it decrypts there, and checks it. No value is ever written in clear, put on a command line, or recorded in a plan or a receipt.
type Secrets struct {
	Roster       *Roster
	rosterDigest string
	Private      git.WorkTree
	Transport    Copier
	Runner       Runner
	// Now stamps receipts and commits.
	Now func() time.Time
}

// LoadSecrets reads roster.toml in the private config checkout.
func LoadSecrets(private git.WorkTree, t Copier, run Runner) (*Secrets, error) {
	data, err := os.ReadFile(filepath.Join(private.Dir, "roster.toml"))
	if err != nil {
		return nil, err
	}
	roster, err := ParseRoster(data)
	if err != nil {
		return nil, err
	}
	return &Secrets{Roster: roster, rosterDigest: string(digest.Of(data)), Private: private, Transport: t, Runner: run, Now: time.Now}, nil
}

func (s *Secrets) signature() git.Signature {
	return git.Signature{Name: "Guildhall Steward", Email: "steward@guildhall.invalid", When: s.Now().UTC()}
}

// lock takes the private config's .rollout.lock through privateLock, shared with rollouts, collections and
// takeovers, or fails with a *BusyError that names the lock's owner.
func (s *Secrets) lock() (func(), error) {
	return privateLock(s.Private.Dir, s.Now())
}

// SetResult is what Set committed: the machine's file, the names it now holds, its digest and the commit.
type SetResult struct {
	Machine string   `json:"machine"`
	Name    string   `json:"name"`
	File    string   `json:"file"`
	Names   []string `json:"names"`
	SHA256  string   `json:"sha256"`
	Commit  string   `json:"commit"`
	Pushed  bool     `json:"pushed"`
	// Rotated are the retired machines whose rotation of this name on this machine the set closed; Unrotated those
	// still waiting, as the value set is the one the retired machine could read.
	Rotated   []string `json:"rotated,omitempty"`
	Unrotated []string `json:"unrotated,omitempty"`
}

// Set gives machine's secrets file name with value: it decrypts the committed file, if there is one, with the
// recovery key at recoveryKey, in memory, adds or replaces name, encrypts the result to the machine's key and the
// recovery key with sops, and commits only that file and the generated .sops.yaml through a private index, then pushes
// the checkout. It holds .rollout.lock throughout. The value is never written in clear or put on a command line, and
// no error names it. A failed push is returned with the commit made, which stays.
func (s *Secrets) Set(ctx context.Context, machine, name, value, recoveryKey string) (*SetResult, error) {
	m, ok := s.Roster.Machine(machine)
	switch {
	case !ok:
		return nil, fmt.Errorf("machine %q is not in the roster", machine)
	case m.AgeRecipient == "":
		return nil, fmt.Errorf("machine %q has no age_recipient in the roster; run guildhall secrets init there and add the public key it prints", machine)
	case !secrets.ValidName(name):
		return nil, fmt.Errorf("%q is not an environment variable name", name)
	}
	if err := secrets.CheckValue(value); err != nil {
		return nil, err
	}
	sopsConfig, err := SopsConfig(s.Roster)
	if err != nil {
		return nil, err
	}
	release, err := s.lock()
	if err != nil {
		return nil, err
	}
	defer release()
	head, err := s.Private.Head(ctx)
	if err != nil {
		return nil, err
	}
	file := SecretsFile(machine)
	values, err := s.decryptCommitted(ctx, head, file, recoveryKey)
	if err != nil {
		return nil, err
	}
	ciphertext, err := secrets.Encrypt(ctx, values.With(name, value), s.Roster.recipients(m))
	if err != nil {
		return nil, err
	}
	names, _, _ := secrets.Ciphertext(ciphertext)
	res := &SetResult{Machine: machine, Name: name, File: file, Names: names, SHA256: digest.Of(ciphertext).Hex()}
	files := map[string][]byte{file: ciphertext, SopsConfigFile: sopsConfig}
	// A retirement waiting for a new value of name on this machine closes that rotation in the same commit, unless
	// the value is one the retired machine could read: the one this machine held, or the one in the retired machine's
	// own file, decrypted at the commit its plan read it at (docs/secrets.md#retiring-a-machine).
	retirements, err := s.openRetirements(ctx, head)
	if err != nil {
		return nil, err
	}
	old, held := values.Get(name)
	for _, r := range retirements {
		stale := false
		if r.waits(name, machine) {
			stale = held && old == value
			if !stale && r.FileCommit != "" {
				retired, err := s.decryptCommitted(ctx, r.FileCommit, r.File, recoveryKey)
				if err != nil {
					return nil, fmt.Errorf("reading %s as retired machine %s held it: %w", r.File, r.Machine, err)
				}
				was, ok := retired.Get(name)
				stale = ok && was == value
			}
		}
		switch {
		case stale:
			res.Unrotated = append(res.Unrotated, r.Machine)
		case r.close(name, machine, ClosedBySet, s.Now().UTC()):
			files[RetiredFile(r.Machine)] = r.encode()
			res.Rotated = append(res.Rotated, r.Machine)
		}
	}
	if res.Commit, err = s.Private.CommitFiles(ctx, files, fmt.Sprintf("Set secret %s for %s", name, machine), s.signature()); err != nil {
		return nil, fmt.Errorf("committing %s: %w", file, err)
	}
	pushed, err := s.Private.Publish(ctx, s.signature())
	if err != nil {
		return res, fmt.Errorf("committed %s as %s but pushing the private config failed: %w", file, res.Commit, err)
	}
	res.Commit, res.Pushed = pushed, true
	return res, nil
}

// decryptCommitted is the values of file as commit head holds it, decrypted in memory with the recovery key, or none
// when head holds no such file.
func (s *Secrets) decryptCommitted(ctx context.Context, head, file, recoveryKey string) (secrets.Values, error) {
	old, ok, err := s.Private.Show(ctx, head, file)
	if err != nil || !ok {
		return secrets.Values{}, err
	}
	if _, err := os.Stat(recoveryKey); err != nil {
		return secrets.Values{}, fmt.Errorf("%s exists, and adding a value decrypts it with the recovery key, but there is none at %s: %w", file, recoveryKey, err)
	}
	tmp, err := os.MkdirTemp("", "guildhall-secrets-")
	if err != nil {
		return secrets.Values{}, err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	// The file is ciphertext; only its decryption, in memory, holds values.
	cipher := filepath.Join(tmp, "secrets.sops.yaml")
	if err := os.WriteFile(cipher, old, 0o600); err != nil {
		return secrets.Values{}, err
	}
	return secrets.Load(ctx, secrets.Paths{Key: recoveryKey, File: cipher}, nil)
}

// SecretsPlan is a dry-run push of machines' secrets files: what each machine has, what it would get, and the
// commands. It holds names and digests, never a value.
type SecretsPlan struct {
	Schema       string           `json:"schema"`
	Digest       string           `json:"digest"`
	RosterDigest string           `json:"roster_digest"`
	Commit       string           `json:"commit"`
	Machines     []string         `json:"machines"`
	StageDir     string           `json:"stage_dir"`
	Pushes       []MachineSecrets `json:"pushes"`
}

// MachineSecrets is one machine's part of a secrets plan.
type MachineSecrets struct {
	Machine   string `json:"machine"`
	SSHAlias  string `json:"ssh_alias"`
	Recipient string `json:"recipient,omitempty"`
	// Source is the committed ciphertext, below the private config; Target its place on the machine, where secrets
	// install renames it from newTarget.
	Source  string   `json:"source"`
	Target  string   `json:"target"`
	Status  string   `json:"status"`
	Problem string   `json:"problem,omitempty"`
	Names   []string `json:"names,omitempty"`
	// BeforeSHA256 is the machine's file now, empty when it has none; AfterSHA256 the committed ciphertext's.
	BeforeSHA256 string `json:"before_sha256,omitempty"`
	AfterSHA256  string `json:"after_sha256,omitempty"`
	// Commands are the scp put of the ciphertext beside the machine's file and its read-back, then the ssh commands
	// that run secrets install and, last, secrets check.
	Commands [][]string `json:"commands,omitempty"`

	ciphertext []byte
	check      []string
	install    []string
}

func (p MachineSecrets) stage(stageDir string) string {
	return filepath.Join(stageDir, "files", p.Machine)
}

// newTarget is where the push drops the ciphertext on the machine, beside Target, so the rename that installs it
// stays on one filesystem and the live file is untouched until it decrypts there.
func (p MachineSecrets) newTarget() string { return secrets.NewFile(p.Target, p.AfterSHA256) }

func (p MachineSecrets) transfers(input, verify string) []transfer {
	dropped := Remote{p.SSHAlias, p.newTarget()}
	return []transfer{{local: input, remote: dropped, put: true}, {local: verify, remote: dropped}}
}

// Plan reads each named machine's committed ciphertext at the checkout's HEAD and runs secrets check there, changing
// nothing. A machine is refused when it is not a Linux or macOS machine with a Director copy, has no age_recipient,
// has no committed file or one not encrypted to exactly its key and the recovery key, or cannot be checked, or its
// key is not the roster's.
func (s *Secrets) Plan(ctx context.Context, machines []string, stageDir string) (*SecretsPlan, error) {
	if len(machines) == 0 {
		return nil, errors.New("name at least one enrolled machine")
	}
	if s.Roster.RecoveryRecipient == "" {
		return nil, errors.New("the roster has no recovery_recipient, the Guildmaster's recovery key every secrets file is also encrypted to")
	}
	stageDir, err := filepath.Abs(stageDir)
	if err != nil {
		return nil, err
	}
	head, err := s.Private.Head(ctx)
	if err != nil {
		return nil, err
	}
	p := &SecretsPlan{Schema: SecretsPlanSchema, RosterDigest: s.rosterDigest, Commit: head, Machines: machines, StageDir: stageDir, Pushes: []MachineSecrets{}}
	for i, label := range machines {
		if slices.Contains(machines[:i], label) {
			return nil, fmt.Errorf("machine %q is named twice", label)
		}
		m, ok := s.Roster.Machine(label)
		if !ok {
			return nil, fmt.Errorf("machine %q is not enrolled in the roster; enrolment comes first", label)
		}
		ms := MachineSecrets{Machine: m.Label, SSHAlias: m.SSHAlias, Recipient: m.AgeRecipient, Source: SecretsFile(m.Label), Target: RemoteSecretsFile}
		s.planMachine(ctx, &ms, m, head, stageDir)
		p.Pushes = append(p.Pushes, ms)
	}
	p.Digest = planDigest(*p)
	return p, nil
}

func planDigest(p SecretsPlan) string {
	p.Digest = ""
	data, err := json.Marshal(&p)
	if err != nil {
		panic(err) // A plan is plain data and always encodes.
	}
	return string(digest.Of(data))
}

func (s *Secrets) planMachine(ctx context.Context, ms *MachineSecrets, m Machine, head, stageDir string) {
	refuse := func(format string, args ...any) { ms.Status, ms.Problem = StatusRefused, fmt.Sprintf(format, args...) }
	switch {
	case m.OS == OSWindows:
		refuse("secrets are not pushed to Windows machines yet (R1.27)")
		return
	case len(m.Directors) == 0:
		refuse("the machine has no Director copy to run secrets check in")
		return
	case m.AgeRecipient == "":
		refuse("no age_recipient in the roster; run guildhall secrets init on the machine and add the public key it prints")
		return
	}
	data, ok, err := s.Private.Show(ctx, head, ms.Source)
	switch {
	case err != nil:
		refuse("reading %s: %v", ms.Source, err)
		return
	case !ok:
		refuse("the private config has no %s committed; give it a value with guildhall steward secrets set", ms.Source)
		return
	}
	names, recipients, err := secrets.Ciphertext(data)
	if err != nil {
		refuse("%s: %v", ms.Source, err)
		return
	}
	if want := s.Roster.recipients(m); !slices.Equal(recipients, want) {
		refuse("%s is encrypted to %s, not to the machine's key and the recovery key %s; set a value again to re-encrypt it", ms.Source, strings.Join(recipients, ","), strings.Join(want, ","))
		return
	}
	ms.Names, ms.ciphertext, ms.AfterSHA256 = names, data, digest.Of(data).Hex()
	ms.check = SecretsCheckCommand(m.Guildhall(), m.Directors[0].CopyDir)
	report, _, err := s.check(ctx, ms)
	if err != nil {
		refuse("%v", err)
		return
	}
	switch {
	case !report.KeyExists:
		refuse("the machine has no key at %s; run guildhall secrets init there", report.Key)
		return
	case report.Recipient != m.AgeRecipient:
		refuse("the machine's key %s has the public key %q, not the roster's age_recipient %s", report.Key, report.Recipient, m.AgeRecipient)
		return
	case !strings.HasSuffix(filepath.ToSlash(report.File), "/"+RemoteSecretsFile):
		refuse("the machine reads its secrets file at %s, not at ~/%s where the Steward publishes it", report.File, RemoteSecretsFile)
		return
	}
	ms.BeforeSHA256 = report.FileSHA256
	if ms.BeforeSHA256 == ms.AfterSHA256 {
		ms.Status = StatusUnchanged
		return
	}
	if !report.Installs {
		// An older guildhall's report has no installs field: it cannot run secrets install, so apply would fail there
		// after the put. Refuse before anything is copied.
		refuse("the machine's guildhall predates secrets install; upgrade guildhall on the machine")
		return
	}
	ms.Status = StatusChange
	ms.install = SecretsInstallCommand(m.Guildhall(), ms.AfterSHA256, m.Directors[0].CopyDir)
	stage := ms.stage(stageDir)
	for _, x := range ms.transfers(filepath.Join(stage, secrets.File), filepath.Join(stage, "verify.sops.yaml")) {
		ms.Commands = append(ms.Commands, x.command())
	}
	ms.Commands = append(ms.Commands, sshCommand(ms.SSHAlias, ms.install), sshCommand(ms.SSHAlias, ms.check))
}

// check runs secrets check on the machine and reads its report.
func (s *Secrets) check(ctx context.Context, ms *MachineSecrets) (secrets.Report, []byte, error) {
	var r secrets.Report
	if s.Runner == nil {
		return r, nil, errors.New("no remote command runner")
	}
	out, err := s.Runner.Run(ctx, ms.SSHAlias, ms.check)
	if err != nil {
		return r, nil, fmt.Errorf("secrets check: %w", err)
	}
	if err := json.Unmarshal(out, &r); err != nil {
		return r, out, fmt.Errorf("secrets check printed no report: %w", err)
	}
	return r, out, nil
}

// WriteSecretsPlan writes plan.json and each changed machine's ciphertext into a new stage directory.
func WriteSecretsPlan(p *SecretsPlan) error {
	if _, err := os.Stat(filepath.Join(p.StageDir, "plan.json")); err == nil {
		return fmt.Errorf("%s already holds a plan; use a new directory", p.StageDir)
	}
	for _, ms := range p.Pushes {
		if ms.Status != StatusChange {
			continue
		}
		stage := ms.stage(p.StageDir)
		if err := os.MkdirAll(stage, 0o700); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(stage, secrets.File), ms.ciphertext, 0o600); err != nil {
			return err
		}
	}
	data, err := json.MarshalIndent(p, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(p.StageDir, 0o700); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(p.StageDir, "plan.json"), append(data, '\n'), 0o600)
}

// ReadSecretsPlan reads a plan written by WriteSecretsPlan.
func ReadSecretsPlan(stageDir string) (*SecretsPlan, error) {
	data, err := os.ReadFile(filepath.Join(stageDir, "plan.json"))
	if err != nil {
		return nil, err
	}
	var p SecretsPlan
	if err := strictjson.Decode(data, &p, strictjson.Options{Schema: secretsPlanSchemaPrefix, Version: secretsPlanSchemaVersion}); err != nil {
		return nil, fmt.Errorf("secrets plan: %w", err)
	}
	return &p, nil
}

// IsSecretsPlan reports whether planDir holds a secrets plan rather than a rollout or setup plan.
func IsSecretsPlan(planDir string) bool {
	data, err := os.ReadFile(filepath.Join(planDir, "plan.json"))
	if err != nil {
		return false
	}
	var head struct {
		Schema string `json:"schema"`
	}
	return json.Unmarshal(data, &head) == nil && strings.HasPrefix(head.Schema, secretsPlanSchemaPrefix)
}

// SecretsReceipt records what a secrets push did on each machine, by names and digests only.
type SecretsReceipt struct {
	Schema     string                  `json:"schema"`
	PlanDigest string                  `json:"plan_digest"`
	Commit     string                  `json:"commit"`
	StartedAt  time.Time               `json:"started_at"`
	FinishedAt time.Time               `json:"finished_at"`
	Machines   []MachineSecretsReceipt `json:"machines"`
	// File is where the receipt was written.
	File string `json:"-"`
}

// MachineSecretsReceipt is one machine's outcome.
type MachineSecretsReceipt struct {
	Machine        string   `json:"machine"`
	Target         string   `json:"target"`
	Status         string   `json:"status"`
	Names          []string `json:"names"`
	BeforeSHA256   string   `json:"before_sha256,omitempty"`
	AfterSHA256    string   `json:"after_sha256"`
	VerifiedSHA256 string   `json:"verified_sha256,omitempty"`
	Steps          []Step   `json:"steps,omitempty"`
	Error          string   `json:"error,omitempty"`
}

// Apply carries out the dry-run secrets plan in stageDir, which every push needs approved: approve must be its
// digest. Holding .rollout.lock, it plans again and refuses unless the result is identical and the staged ciphertext
// intact; then, on each machine that changes, it copies the ciphertext beside the machine's secrets file, reads it
// back and compares its digest, runs secrets install, which swaps it in only once it decrypts with the machine's own
// key, keeping the old file as .prev, and runs secrets check, which must find the installed file decrypting to the
// planned names. Until install renames it, the machine's secrets file is untouched. A machine that fails does not stop the others; the receipt, written to stageDir, records each.
func (s *Secrets) Apply(ctx context.Context, stageDir, approve string, machines ...string) (*SecretsReceipt, error) {
	saved, err := ReadSecretsPlan(stageDir)
	if err != nil {
		return nil, err
	}
	if !slices.Equal(slices.Sorted(slices.Values(machines)), slices.Sorted(slices.Values(saved.Machines))) {
		return nil, errors.New("requested machines differ from saved plan; use its exact machine set or create a new plan")
	}
	release, err := s.lock()
	if err != nil {
		return nil, err
	}
	defer release()
	if abs, err := filepath.Abs(stageDir); err != nil || abs != saved.StageDir {
		return nil, fmt.Errorf("%w: the plan was written for %s", ErrPlanStale, saved.StageDir)
	}
	p, err := s.Plan(ctx, saved.Machines, saved.StageDir)
	if err != nil {
		return nil, err
	}
	if p.Digest != saved.Digest {
		return nil, ErrPlanStale
	}
	for _, ms := range p.Pushes {
		if ms.Status == StatusRefused {
			return nil, ErrNotApplicable
		}
	}
	if approve != p.Digest {
		return nil, ErrApprovalRequired
	}
	for _, ms := range p.Pushes {
		if ms.Status != StatusChange {
			continue
		}
		staged, err := os.ReadFile(filepath.Join(ms.stage(p.StageDir), secrets.File))
		if err != nil || !bytes.Equal(staged, ms.ciphertext) {
			return nil, fmt.Errorf("%w: the staged secrets file for %s changed", ErrPlanStale, ms.Machine)
		}
	}
	receipt := &SecretsReceipt{Schema: SecretsReceiptSchema, PlanDigest: p.Digest, Commit: p.Commit, StartedAt: s.Now().UTC()}
	complete := true
	for _, ms := range p.Pushes {
		mr := s.applyMachine(ctx, ms, p.StageDir)
		complete = complete && (mr.Status == StatusApplied || mr.Status == StatusUnchanged)
		receipt.Machines = append(receipt.Machines, mr)
	}
	receipt.FinishedAt = s.Now().UTC()
	data, err := json.MarshalIndent(receipt, "", "  ")
	if err != nil {
		return receipt, err
	}
	file := filepath.Join(p.StageDir, "receipt-"+receipt.StartedAt.Format("20060102T150405Z")+".json")
	if err := os.WriteFile(file, append(data, '\n'), 0o600); err != nil {
		return receipt, err
	}
	receipt.File = file
	if !complete {
		return receipt, ErrIncomplete
	}
	return receipt, nil
}

func (s *Secrets) applyMachine(ctx context.Context, ms MachineSecrets, stageDir string) MachineSecretsReceipt {
	mr := MachineSecretsReceipt{Machine: ms.Machine, Target: ms.Target, Status: ms.Status, Names: ms.Names,
		BeforeSHA256: ms.BeforeSHA256, AfterSHA256: ms.AfterSHA256}
	if mr.Names == nil {
		mr.Names = []string{}
	}
	if ms.Status != StatusChange {
		return mr
	}
	fail := func(status string, err error) MachineSecretsReceipt {
		mr.Status, mr.Error = status, err.Error()
		return mr
	}
	inputs, err := os.MkdirTemp(stageDir, ".apply-")
	if err != nil {
		return fail(StatusFailed, err)
	}
	defer func() { _ = os.RemoveAll(inputs) }()
	input := filepath.Join(inputs, secrets.File)
	if err := os.WriteFile(input, ms.ciphertext, 0o600); err != nil {
		return fail(StatusFailed, err)
	}
	verify := filepath.Join(ms.stage(stageDir), "verify.sops.yaml")
	for _, x := range ms.transfers(input, verify) {
		step := Step{Command: x.command()}
		err := x.run(ctx, s.Transport)
		if err != nil {
			step.Error = err.Error()
		}
		mr.Steps = append(mr.Steps, step)
		if err != nil {
			return fail(StatusFailed, err)
		}
	}
	got, err := os.ReadFile(verify)
	if err != nil {
		return fail(StatusFailed, err)
	}
	mr.VerifiedSHA256 = digest.Of(got).Hex()
	if mr.VerifiedSHA256 != ms.AfterSHA256 {
		return fail(StatusVerifyFailed, errors.New("the secrets file read back does not match the pushed ciphertext"))
	}
	// Install's report holds names and digests only, never a value; a refusal's report is in the error, as the runner
	// reports a command that exits non-zero.
	install := Step{Command: sshCommand(ms.SSHAlias, ms.install)}
	out, err := s.Runner.Run(ctx, ms.SSHAlias, ms.install)
	install.Output = strings.TrimSpace(string(out))
	if err == nil {
		var r secrets.InstallReport
		if jerr := json.Unmarshal(out, &r); jerr != nil {
			err = fmt.Errorf("secrets install printed no report: %w", jerr)
		} else if !r.Installed {
			err = fmt.Errorf("secrets install refused at %s: %s", r.Step, r.Problem)
		}
	}
	if err != nil {
		install.Error = err.Error()
		mr.Steps = append(mr.Steps, install)
		return fail(StatusInstallFailed, fmt.Errorf("secrets install: %w", err))
	}
	mr.Steps = append(mr.Steps, install)
	step := Step{Command: sshCommand(ms.SSHAlias, ms.check)}
	report, out, err := s.check(ctx, &ms)
	if err != nil {
		step.Error = err.Error()
		mr.Steps = append(mr.Steps, step)
		return fail(StatusCheckFailed, err)
	}
	// The report holds names and digests only, never a value.
	step.Output = strings.TrimSpace(string(out))
	mr.Steps = append(mr.Steps, step)
	switch {
	case !report.Decrypts:
		return fail(StatusCheckFailed, fmt.Errorf("the machine's key does not decrypt the pushed file: %s", report.Problem))
	case report.FileSHA256 != ms.AfterSHA256:
		return fail(StatusCheckFailed, fmt.Errorf("the machine's secrets file has digest %s, not the pushed %s", report.FileSHA256, ms.AfterSHA256))
	case !slices.Equal(report.Names, ms.Names):
		return fail(StatusCheckFailed, fmt.Errorf("the machine's secrets file decrypts to the names %s, not %s", strings.Join(report.Names, ","), strings.Join(ms.Names, ",")))
	}
	mr.Status = StatusApplied
	return mr
}
